#!/usr/bin/env python3
"""Demo "stage": one full-screen page showing the PipeCD console, the live app,
live traffic and a terminal. Open http://localhost:7700 in a browser (fullscreen).

  python3 stage/server.py            # needs: kubectl context pointing at the demo cluster,
                                     #        PipeCD console port-forwarded on :8080

Traffic is generated by the page itself (20 req/s) through `kubectl proxy`, using
the API server's service proxy, which picks a random ready pod per request, so the
mix of versions you see matches the real primary/canary pod ratio.
"""
import json
import os
import subprocess
import time
import urllib.error
import urllib.request
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
TERM_LOG = os.path.join(HERE, ".terminal.log")
STATE = os.path.join(HERE, ".state.json")
PROXY = "http://127.0.0.1:8001/api/v1/namespaces/demo/services/web:8080/proxy"
PORT = int(os.environ.get("STAGE_PORT", "7700"))


class Handler(SimpleHTTPRequestHandler):
    def __init__(self, *a, **kw):
        super().__init__(*a, directory=HERE, **kw)

    def log_message(self, *a):
        pass

    def _send(self, code, body, ctype="application/json"):
        data = body if isinstance(body, bytes) else body.encode()
        self.send_response(code)
        self.send_header("Content-Type", ctype)
        self.send_header("Cache-Control", "no-store")
        self.send_header("Content-Length", str(len(data)))
        self.end_headers()
        self.wfile.write(data)

    def do_GET(self):
        if self.path.startswith("/app/"):
            try:
                with urllib.request.urlopen(PROXY + self.path[4:], timeout=2) as r:
                    return self._send(r.status, r.read())
            except urllib.error.HTTPError as e:
                body = e.read()
                if e.code == 500 and body.startswith(b"{"):
                    return self._send(500, body)        # the app's own 500 (v2)
                return self._send(e.code, json.dumps({"version": None, "ok": False, "proxy": e.code}))
            except Exception:
                return self._send(503, json.dumps({"version": None, "ok": False, "proxy": 503}))
        if self.path == "/term":
            try:
                return self._send(200, open(TERM_LOG).read(), "text/plain; charset=utf-8")
            except FileNotFoundError:
                return self._send(200, "", "text/plain")
        if self.path == "/state":
            try:
                return self._send(200, open(STATE).read())
            except FileNotFoundError:
                return self._send(200, "{}")
        if self.path.startswith("/file?"):
            rel = self.path.split("=", 1)[1]
            p = os.path.normpath(os.path.join(ROOT, rel))
            if not p.startswith(ROOT + os.sep):
                return self._send(403, "{}")
            return self._send(200, open(p).read(), "text/plain; charset=utf-8")
        return super().do_GET()


if __name__ == "__main__":
    kp = subprocess.Popen(["kubectl", "proxy", "--port=8001"], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    time.sleep(1)
    print(f"stage on http://localhost:{PORT}  (kubectl proxy pid {kp.pid})", flush=True)
    try:
        ThreadingHTTPServer(("127.0.0.1", PORT), Handler).serve_forever()
    finally:
        kp.terminate()
